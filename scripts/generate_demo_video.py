def main():
    print(f"--- Starting Full HD Demo Video Generation for PayLens ---")
    temp_dir = tempfile.mkdtemp(prefix="paylens_demo_")
    frames_dir = os.path.join(temp_dir, "frames")
    os.makedirs(frames_dir, exist_ok=True)

    # 1. Generate Audio Tracks
    audio_tracks = generate_audio_tracks(temp_dir)

    # 2. Render all video frames matching audio timing
    total_frames = sum(t["frame_count"] for t in audio_tracks)
    print(f"Rendering {total_frames} video frames at {WIDTH}x{HEIGHT} ({FPS} fps)...")

    global_frame = 0
    for t in audio_tracks:
        s_idx = t["idx"]
        s_frames = t["frame_count"]
        for sf in range(s_frames):
            frame_img = render_frame(global_frame, s_idx, sf, s_frames)
            frame_filename = os.path.join(frames_dir, f"frame_{global_frame:05d}.png")
            frame_img.save(frame_filename)
            global_frame += 1
            if global_frame % 50 == 0 or global_frame == total_frames:
                print(f"  Rendered {global_frame}/{total_frames} frames ({global_frame/total_frames*100:.1f}%)")

    # 3. Concatenate Scene Audio with ffmpeg
    concat_list_path = os.path.join(temp_dir, "audio_concat.txt")
    with open(concat_list_path, "w", encoding="utf-8") as f:
        for t in audio_tracks:
            # ffmpeg concat demuxer format
            p = t["wav_path"].replace("\\", "/")
            f.write(f"file '{p}'\n")

    full_audio_wav = os.path.join(temp_dir, "full_audio.wav")
    print("Concatenating audio tracks...")
    subprocess.run([
        "ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", concat_list_path,
        "-c", "copy", full_audio_wav
    ], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    # 4. Encode Final MP4 with ffmpeg (H.264 + AAC, faststart for streaming)
    print(f"Encoding final MP4 video at {OUTPUT_MP4}...")
    subprocess.run([
        "ffmpeg", "-y",
        "-framerate", str(FPS),
        "-i", os.path.join(frames_dir, "frame_%05d.png"),
        "-i", full_audio_wav,
        "-c:v", "libx264",
        "-pix_fmt", "yuv420p",
        "-preset", "fast",
        "-crf", "22",
        "-c:a", "aac",
        "-b:a", "192k",
        "-shortest",
        "-movflags", "+faststart",
        OUTPUT_MP4,
    ], check=True)

    file_size_mb = os.path.getsize(OUTPUT_MP4) / (1024 * 1024)
    print(f"✓ HD Demo Video generated successfully: {OUTPUT_MP4} ({file_size_mb:.2f} MB)")


if __name__ == "__main__":
    main()
