    d = ImageDraw.Draw(img)

    # State variables depending on scene
    # Scene 0 (Intro): Overview, Sankey static, 3 compact cards
    # Scene 1 (Flow): Sankey animating, 3 compact cards
    # Scene 2 (Agent): Card 1 expands, Agent tool trace active
    # Scene 3 (Grounding): Card 1 expanded, Grounding box turns emerald green
    # Scene 4 (Recovery): Card 1 approved, counter rolling up, SHA-256 appears
    is_expanded = scene_idx >= 2
    is_grounded = scene_idx >= 3
    is_approved = scene_idx >= 4

    recovered_val = 0.0
    grounding_status = "Regex Audited"

    if is_approved:
        prog = min(1.0, scene_frame_idx / float(scene_total_frames * 0.6))
        recovered_val = round(prog * 14200.0, 2)
        grounding_status = "Verified (3/3)"

    draw_header(d, global_frame_idx)
    draw_kpis(d, recovered_val, grounding_status, global_frame_idx)

    sankey_prog = (global_frame_idx % 48) / 48.0
    draw_sankey_flow(d, sankey_prog)

    explain_str = "Lumina Smart Home: Dispatched order ORD-3143 has no confirmed payment on Stripe rail. Consignment CONS-SHORT-9001 on DHL Express settled $686.00 against expected $806.00, yielding a $120.00 tariff shortfall."

