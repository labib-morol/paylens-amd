def generate_audio_tracks(temp_dir: str) -> list:
    """Uses PowerShell System.Speech to generate narration audio for each scene."""
    audio_files = []
    print("Generating scene audio narrations using Windows Speech Engine...")
    for idx, scene in enumerate(SCENES):
        wav_path = os.path.join(temp_dir, f"scene_{idx}.wav")
        # Build PS1 script
        ps1_path = os.path.join(temp_dir, f"tts_{idx}.ps1")
        text_escaped = scene["narration"].replace("'", "''")
        ps1_content = f"""Add-Type -AssemblyName System.Speech
$synth = New-Object System.Speech.Synthesis.SpeechSynthesizer
$synth.SelectVoice('Microsoft Zira Desktop')
$synth.Rate = 0
$synth.SetOutputToWaveFile('{wav_path.replace("\\", "/")}')
$synth.Speak('{text_escaped}')
$synth.Dispose()
"""
        with open(ps1_path, "w", encoding="utf-8") as f:
            f.write(ps1_content)

        subprocess.run(["powershell", "-ExecutionPolicy", "Bypass", "-File", ps1_path], check=True, stdout=subprocess.DEVNULL)

        # Get duration from wave
        with wave.open(wav_path, "rb") as wf:
            frames = wf.getnframes()
            rate = wf.getframerate()
            duration = frames / float(rate)

        # Add 0.8s padding to each scene for smooth pacing
        total_scene_sec = duration + 0.8
        audio_files.append({
            "idx": idx,
            "scene": scene,
            "wav_path": wav_path,
            "audio_duration": duration,
            "scene_duration": total_scene_sec,
            "frame_count": int(total_scene_sec * FPS),
        })
        print(f"  Scene {idx+1}: {scene['id']} -> {duration:.1f}s ({int(total_scene_sec * FPS)} frames)")

    return audio_files


